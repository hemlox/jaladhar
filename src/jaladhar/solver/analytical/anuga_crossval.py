"""ANUGA three-way cross-validation for the ACC local-inertial shallow water solver.

EXTERNAL CORRECTNESS EVIDENCE (CLAUDE.md V1-V8):
ANUGA solves the FULL shallow-water equations (SWE) including nonlinear advection
and shock capturing on an unstructured triangular mesh.
ACC (Bates et al. 2010) drops nonlinear advection (u * du/dx) on a regular grid.

This module evaluates all three models — Analytical closed-form, ACC, and ANUGA —
on identical benchmark configurations:
  1. Ritter (1892) dry-bed dam break (high Froude, Fr >= 1.0, advection-dominated)
  2. Stoker (1957) wet-bed dam break (high Froude, Fr ~ 1.18, shock-forming)
  3. Thacker (1981) oscillating parabolic bowl (low Froude, Fr = 0.028, du/dx = 0)
  4. MacDonald (1997) steady subcritical channel flow with friction (low Froude, Fr ~ 0.32)

MAPPING METHODOLOGY:
ANUGA discretises the domain using an unstructured triangular mesh generated by
`anuga.rectangular_cross_domain(nx, ny, len1=Lx, len2=Ly)`, where flow variables
(stage, elevation, momentum) are stored at triangle centroids (x_c, y_c).
The ACC solver operates on a regular Cartesian 2D grid with cell centers x_acc.
Because all benchmark cases are 1D along x (invariant in y), we map ANUGA's
centroid depths onto ACC's regular cell centers x_acc via 1D piecewise linear
interpolation (`np.interp` on coordinates sorted by x).
All three depth distributions — Analytical h_exact(x_acc), ACC h_acc(x_acc),
and ANUGA h_anuga(x_acc) — are therefore evaluated at identical sample coordinates
x_acc, allowing pointwise L1 and L2 norm calculations without spatial skew.
"""

