def git_sha() -> str:
    """CLAUDE.md Rule 6: Recover exact git SHA for run manifest."""
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL, cwd=REPO
        ).strip()
    except Exception:
        return "unknown"


def _cfg(**overrides) -> dict[str, Any]:
    cfg = load_solver_config(CONFIG, REPO)
    for dotted, value in overrides.items():
        section, key = dotted.split(".", 1)
        cfg[section][key] = value
    return cfg


def _params(dx: float, **overrides) -> SolverParams:
    cfg = _cfg(**overrides)
    return SolverParams.from_config(cfg, dx)


@dataclass
class ThreeWayResult:
    case_name: str
    froude: float
    regime: str
    dx_m: float
    l1_analytical_vs_acc: float
    l2_analytical_vs_acc: float
    l1_analytical_vs_anuga: float
    l2_analytical_vs_anuga: float
    l1_acc_vs_anuga: float
    l2_acc_vs_anuga: float
    notes: str


def run_ritter_crossval(
    dx: float = 2.5, length_m: float = 200.0, t_eval: float = 4.0, h0: float = 1.0
) -> ThreeWayResult:
    """Ritter (1892) dry-bed dam break cross-validation."""
    ritter = RitterCase(h0=h0)

    # 1. ACC simulation
    static, x_acc, h0_tensor = ritter.make_domain(length_m=length_m, dx=dx, device="cpu")
    p = _params(
        dx,
        **{
            "boundaries.mode": "closed",
            "wetdry.mode": "hard",
            "timestep.cfl_alpha": 0.5,
            "timestep.max_dt_s": 10.0,
        },
    )
    ctrl = TimestepController(dx=dx, alpha=0.5, max_dt_s=10.0)
    res = simulate(static, p, ctrl, duration_s=t_eval, h0=h0_tensor)
    h_acc = res.h[1, :].numpy()

    # 2. ANUGA simulation
    nx = int(round(length_m / dx))
    domain = anuga.rectangular_cross_domain(nx, 4, len1=length_m, len2=10.0)
    domain.set_quantity("elevation", 0.0)
    domain.set_quantity("friction", 0.0)
    domain.set_quantity("stage", lambda x, y: np.where(x <= (length_m / 2.0), h0, 0.0))
    domain.set_boundary(
        {
            "left": anuga.Reflective_boundary(domain),
            "right": anuga.Reflective_boundary(domain),
            "top": anuga.Reflective_boundary(domain),
            "bottom": anuga.Reflective_boundary(domain),
        }
    )
    domain.set_quantities_to_be_stored(None)
    for _ in domain.evolve(yieldstep=1.0, finaltime=t_eval):
        pass

    depth_anuga = (
        domain.quantities["stage"].centroid_values
        - domain.quantities["elevation"].centroid_values
    )
    coords = domain.get_centroid_coordinates()
    x_anuga = coords[:, 0] - (length_m / 2.0)

    # Interpolate ANUGA centroid depths onto ACC cell centres
    sort_idx = np.argsort(x_anuga)
    h_anuga_interp = np.interp(x_acc, x_anuga[sort_idx], depth_anuga[sort_idx])

    # Exact solution
    h_exact = ritter.exact_h(x_acc, t_eval)

    l1_an_acc = float(np.mean(np.abs(h_exact - h_acc)))
    l2_an_acc = float(np.sqrt(np.mean((h_exact - h_acc) ** 2)))
    l1_an_anuga = float(np.mean(np.abs(h_exact - h_anuga_interp)))
    l2_an_anuga = float(np.sqrt(np.mean((h_exact - h_anuga_interp) ** 2)))
    l1_acc_anuga = float(np.mean(np.abs(h_acc - h_anuga_interp)))
    l2_acc_anuga = float(np.sqrt(np.mean((h_acc - h_anuga_interp) ** 2)))

    return ThreeWayResult(
        case_name="Ritter (1892)",
        froude=float(np.max(ritter.froude(x_acc, t_eval))),
        regime="High-Froude (advection-dominated)",
        dx_m=dx,
        l1_analytical_vs_acc=l1_an_acc,
        l2_analytical_vs_acc=l2_an_acc,
        l1_analytical_vs_anuga=l1_an_anuga,
        l2_analytical_vs_anuga=l2_an_anuga,
        l1_acc_vs_anuga=l1_acc_anuga,
        l2_acc_vs_anuga=l2_acc_anuga,
        notes="ANUGA matches analytical (<0.007m); ACC-vs-ANUGA gap measures advection omission.",
    )


