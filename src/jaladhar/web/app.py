def _parse_int(value: Any, *, field: str, row_number: int | None = None) -> int:
    location = f" at row {row_number}" if row_number is not None else ""
    if isinstance(value, bool):
        raise ContractViolation(f"{field}{location} must be an integer, not a boolean")
    if isinstance(value, int):
        return value
    if isinstance(value, str) and re.fullmatch(r"[+-]?\d+", value.strip()):
        return int(value.strip())
    raise ContractViolation(f"{field}{location} must be an integer")


def _parse_timestamp(value: Any, *, field: str, row_number: int) -> datetime:
    if not isinstance(value, str) or not value.strip():
        raise ContractViolation(f"{field} at row {row_number} must be an ISO8601 UTC timestamp")
    text = value.strip()
    if text.endswith("Z"):
        text = f"{text[:-1]}+00:00"
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError as exc:
        raise ContractViolation(f"{field} at row {row_number} is not ISO8601: {value!r}") from exc
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise ContractViolation(f"{field} at row {row_number} must be timezone-aware UTC")
    if parsed.utcoffset() != UTC.utcoffset(parsed):
        raise ContractViolation(f"{field} at row {row_number} must carry a UTC offset")
    return parsed.astimezone(UTC)


