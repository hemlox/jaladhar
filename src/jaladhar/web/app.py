"""CPU-only read-only web dashboard for the frozen WF-3 depth product.

The dashboard is deliberately a product reader, not a solver adapter.  It will
serve an empty state until a producer has written a contract-valid segment
product and its source manifest.  No depth, status, geometry, or summary value
is generated by this module.

The HTTP surface is intentionally small:

* ``/`` serves the static dashboard;
* ``/api/state`` exposes the available immutable product snapshots;
* ``/api/segments`` exposes one selected snapshot as GeoJSON;
* ``/api/context/<name>`` serves allowlisted WF-6 context assets from
  ``data/interim/context/`` (wards blobs + meta sidecars, the segment->ward
  join, the search index, the forcing series);
* ``/api/watchlist`` and ``/api/intersections`` run the WF-6 lane builders
  against the store's active realized product (frame param: tag|index|"held");
* ``/api/drains/causal?segment_id=`` maps one street segment onto nearby
  predicted-overcapacity drain edges via an injected midpoint provider over
  the realized centreline GeoPackage.

Run the module with ``python -m jaladhar.web.app serve``.  ``check`` is a
CPU-only smoke check that does not create or mutate a run.
"""

