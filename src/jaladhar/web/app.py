'CPU-only read-only web dashboard for the frozen WF-3 depth product. The dashboard is deliberately a product reader, not a solver adapter. It will serve an empty state until a producer has written a contract-valid segment product and its source manifest. No depth, status, geometry, or summary value is generated by this module. The HTTP surface is intentionally small: * ``/`` serves the static dashboard; * ``/api/state`` exposes the available immutable product snapshots; * ``/api/segments`` exposes one selected snapshot as GeoJSON; * ``/api/context/<name>`` serves allowlisted WF-6 context assets from ``data/interim/context/`` (wards blobs + meta sidecars, the segment->ward join, the search index, the forcing series); * ``/api/watchlist`` and ``/api/intersections`` run the WF-6 lane builders against the store\'s active realized product (frame param: tag|index|"held"); * ``/api/drains/causal?segment_id=`` maps one street segment onto nearby predicted-overcapacity drain edges via an injected midpoint provider over the realized centreline GeoPackage. * ``/api/comparison2022`` streams the realized WF8 sim-vs-sim agreement (runs/wf8_sim_vs_sim_3h_vs_replay/comparison.json) — every number in the strip is read from this file, never hardcoded (rule 3). Honest 404 {"error":"comparison product missing"} when the artifact is absent. Load-once cache, verbatim bytes. * ``/api/comparison2022/observed.json`` is retired: returns 404 {"error":"retired: SAR observed view replaced by sim-vs-sim agreement"}. Response shapes --------------- ``/api/comparison2022``: the WF8 comparison.json object verbatim (keys: kind, banned_note, left, right, offset, counts, metrics, band_cross_tab, provenance) — a cross-model consistency statement, neither panel is an observation; the word accuracy is deliberately absent. ``/api/comparison2022/observed.json``: retired — 404 {"error":"retired: SAR observed view replaced by sim-vs-sim agreement"}. Run the module with ``python -m jaladhar.web.app serve``. ``check`` is a CPU-only smoke check that does not create or mutate a run.'  # noqa: E501

