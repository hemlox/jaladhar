    def _serve_static(self, path: str) -> None:
        relative = "index.html" if path in {"", "/"} else unquote(path.lstrip("/"))
        candidate = (STATIC_ROOT / relative).resolve()
        try:
            candidate.relative_to(STATIC_ROOT.resolve())
        except ValueError:
            _json_response(self, HTTPStatus.NOT_FOUND, {"error": "not found"})
            return
        if not candidate.is_file():
            _json_response(self, HTTPStatus.NOT_FOUND, {"error": "not found"})
            return
        try:
            body = candidate.read_bytes()
        except OSError as exc:
            _json_response(self, HTTPStatus.INTERNAL_SERVER_ERROR, {"error": str(exc)})
            return
        content_type = mimetypes.guess_type(candidate.name)[0] or "application/octet-stream"
        self.send_response(HTTPStatus.OK)
        self.send_header("Content-Type", f"{content_type}; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-cache")
        self.end_headers()
        self.wfile.write(body)

    def _serve_context_asset(self, name: str) -> None:
        content_type = CONTEXT_ASSET_TYPES.get(name)
        if content_type is None:
            _json_response(
                self, HTTPStatus.NOT_FOUND, {"error": f"context asset not served: {name}"}
            )
            return
        path = CONTEXT_ASSET_ALT_PATHS.get(name) or (CONTEXT_DIR / name)
        try:
            body = path.read_bytes()
        except OSError as exc:
            _json_response(
                self,
                HTTPStatus.SERVICE_UNAVAILABLE,
                {"error": f"context asset unavailable: {name}: {exc}"},
            )
            return
        self.send_response(HTTPStatus.OK)
        if content_type == "application/json":
            self.send_header("Content-Type", "application/json; charset=utf-8")
        else:
            self.send_header("Content-Type", content_type)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-cache")
        self.end_headers()
        self.wfile.write(body)

