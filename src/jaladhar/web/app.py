class ContractViolation(ValueError):
    """A realized product failed a frozen producer-consumer assertion."""


class DashboardError(RuntimeError):
    """A dashboard input or static asset could not be served safely."""


def _repo_relative(path: Path, repo_root: Path) -> str:
    try:
        return path.resolve().relative_to(repo_root.resolve()).as_posix()
    except ValueError:
        return str(path.resolve())


def _safe_repo_path(path: Path, repo_root: Path, *, label: str) -> Path:
    resolved = path.expanduser().resolve()
    try:
        resolved.relative_to(repo_root.resolve())
    except ValueError as exc:
        raise DashboardError(f"{label} must be inside the repository: {path}") from exc
    return resolved


def _parse_int(value: Any, *, field: str, row_number: int | None = None) -> int:
    location = f" at row {row_number}" if row_number is not None else ""
    if isinstance(value, bool):
        raise ContractViolation(f"{field}{location} must be an integer, not a boolean")
    if isinstance(value, int):
        return value
    if isinstance(value, str) and re.fullmatch(r"[+-]?\d+", value.strip()):
        return int(value.strip())
    raise ContractViolation(f"{field}{location} must be an integer")


def _parse_timestamp(value: Any, *, field: str, row_number: int) -> datetime:
    if not isinstance(value, str) or not value.strip():
        raise ContractViolation(f"{field} at row {row_number} must be an ISO8601 UTC timestamp")
    text = value.strip()
    if text.endswith("Z"):
        text = f"{text[:-1]}+00:00"
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError as exc:
        raise ContractViolation(f"{field} at row {row_number} is not ISO8601: {value!r}") from exc
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise ContractViolation(f"{field} at row {row_number} must be timezone-aware UTC")
    if parsed.utcoffset() != UTC.utcoffset(parsed):
        raise ContractViolation(f"{field} at row {row_number} must carry a UTC offset")
    return parsed.astimezone(UTC)


def _load_json(path: Path, *, label: str) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ContractViolation(f"could not read {label} {path}: {exc}") from exc


def _contract(repo_root: Path) -> dict[str, Any]:
    path = repo_root / "configs" / "contracts" / "depth_product.json"
    payload = _load_json(path, label="frozen depth-product contract")
    if not isinstance(payload, dict):
        raise DashboardError(f"frozen depth-product contract is not an object: {path}")
    return cast(dict[str, Any], payload)


def _extract_product_rows(payload: Any, *, path: Path) -> list[dict[str, Any]]:
    """Accept the frozen JSON twin's common row/feature envelopes.

    The contract fixes fields, not whether the JSON twin is a bare row array or
    an API envelope.  Geometry is preserved only when the producer supplied it;
    it is never reconstructed from a segment id.
    """

    if isinstance(payload, list):
        raw_rows = payload
    elif isinstance(payload, dict) and isinstance(payload.get("features"), list):
        raw_rows = []
        for feature in payload["features"]:
            if not isinstance(feature, dict) or not isinstance(feature.get("properties"), dict):
                raise ContractViolation(f"JSON product feature has no properties object: {path}")
            row = dict(feature["properties"])
            if feature.get("geometry") is not None:
                row["_geometry"] = feature["geometry"]
            raw_rows.append(row)
    elif isinstance(payload, dict) and isinstance(payload.get("rows"), list):
        raw_rows = payload["rows"]
    elif isinstance(payload, dict) and isinstance(payload.get("segments"), list):
        raw_rows = payload["segments"]
    else:
        raise ContractViolation(
            f"JSON product {path} must be a row array, rows/segments envelope, or "
            "GeoJSON FeatureCollection"
        )

    rows: list[dict[str, Any]] = []
    for number, raw in enumerate(raw_rows, start=2):
        if not isinstance(raw, dict):
            raise ContractViolation(f"JSON product row {number} is not an object: {path}")
        rows.append(dict(raw))
    return rows


def _read_product_rows(path: Path) -> list[dict[str, Any]]:
    suffix = path.suffix.lower()
    if suffix == ".json":
        return _extract_product_rows(_load_json(path, label="depth product"), path=path)
    if suffix != ".csv":
        raise ContractViolation(f"unsupported depth-product format: {path.suffix}")
    try:
        with path.open(newline="", encoding="utf-8") as handle:
            reader = csv.DictReader(handle)
            if reader.fieldnames is None:
                raise ContractViolation(f"CSV depth product has no header: {path}")
            rows = [dict(row) for row in reader]
    except OSError as exc:
        raise ContractViolation(f"could not read CSV depth product {path}: {exc}") from exc
    return rows


def _lookup_ids(repo_root: Path) -> set[int]:
    path = repo_root / "data" / "interim" / "terrain" / "roads_segment_lookup.csv"
    if not path.is_file():
        raise ContractViolation(
            f"required segment lookup is missing: {_repo_relative(path, repo_root)}"
        )
    try:
        with path.open(newline="", encoding="utf-8") as handle:
            reader = csv.DictReader(handle)
            if reader.fieldnames is None or "segment_id" not in reader.fieldnames:
                raise ContractViolation(f"segment lookup has no segment_id column: {path}")
            ids: set[int] = set()
            for number, row in enumerate(reader, start=2):
                ids.add(
                    _parse_int(row.get("segment_id"), field="lookup.segment_id", row_number=number)
                )
    except OSError as exc:
        raise ContractViolation(f"could not read segment lookup {path}: {exc}") from exc
    if not ids:
        raise ContractViolation(f"segment lookup contains no realized ids: {path}")
    return ids


def _manifest_path(repo_root: Path, source_manifest: Any) -> Path:
    if not isinstance(source_manifest, str) or not source_manifest.strip():
        raise ContractViolation("source_manifest_path must be a non-empty repository-relative path")
    raw = Path(source_manifest)
    if raw.is_absolute() or ".." in raw.parts:
        raise ContractViolation("source_manifest_path must remain repository-relative")
    path = repo_root / raw
    try:
        path.resolve().relative_to(repo_root.resolve())
    except ValueError as exc:
        raise ContractViolation("source_manifest_path escapes the repository") from exc
    if not path.is_file():
        raise ContractViolation(f"source manifest does not exist: {source_manifest}")
    return path.resolve()


def _manifest_required(manifest: dict[str, Any], key: str, *, path: Path, repo_root: Path) -> Any:
    if key not in manifest:
        raise ContractViolation(
            f"source manifest {_repo_relative(path, repo_root)} lacks required field {key!r}"
        )
    return manifest[key]


