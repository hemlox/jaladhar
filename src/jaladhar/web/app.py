class RoadMidpoints:
    """Lazy segment_id -> representative-point table over the realized
    centreline GeoPackage (drains.py's documented integrator injection point).

    Streams the GeoPackage ONCE on first use under a lock and keeps only ONE
    EPSG:32643 point per segment -- first vertex of the first part averaged
    with the last vertex of the last part, the same midpoint semantic rail.js
    applies client-side -- so 176k segments cost a small dict, not whole
    geometries. A failed read degrades to ``provide`` returning None; the
    causal payload then carries its designed honest empty state.
    """

    def __init__(self, path: Path) -> None:
        self.path = path
        self.lock = threading.Lock()
        self._points: dict[int, list[float]] | None = None
        self._error: str | None = None

    @property
    def available(self) -> bool:
        return self.path.is_file() and self._error is None

    def _load(self) -> None:
        if self._points is not None or self._error is not None:
            return
        if not self.path.is_file():
            self._error = f"centreline artifact missing: {self.path}"
            return
        try:
            import fiona

            points: dict[int, list[float]] = {}
            with fiona.open(self.path) as source:
                for feature in source:
                    properties = feature.get("properties") or {}
                    try:
                        segment_id = int(properties.get("segment_id"))
                    except (TypeError, ValueError):
                        continue
                    if segment_id in points:
                        continue
                    first = _geometry_first_vertex(feature.get("geometry"))
                    last = _geometry_last_vertex(feature.get("geometry"))
                    if first is None or last is None:
                        continue
                    points[segment_id] = [
                        (first[0] + last[0]) / 2.0,
                        (first[1] + last[1]) / 2.0,
                    ]
            if not points:
                raise DashboardError(f"centreline artifact yielded no midpoints: {self.path}")
            self._points = points
        except Exception as exc:  # noqa: BLE001 - degrade honestly, never guess
            self._error = f"{type(exc).__name__}: {exc}"

    def provide(self, segment_id: str | int) -> list[float] | None:
        with self.lock:
            self._load()
            points = self._points
        if points is None:
            return None
        try:
            point = points[int(segment_id)]
        except (TypeError, ValueError, KeyError):
            return None
        return [point[0], point[1]]


def _geometry_coordinates(geometry: Any) -> Any:
    """Coordinates of a GeoJSON-style geometry dict OR a fiona.model.Geometry
    (fiona >=1.10 hands out its own model objects, which are not dicts but do
    answer ``get("coordinates")``)."""
    if geometry is None:
        return None
    get = getattr(geometry, "get", None)
    if get is not None:
        try:
            return get("coordinates")
        except Exception:  # noqa: BLE001 - fall through to attribute access
            pass
    return getattr(geometry, "coordinates", None)


def _geometry_first_vertex(geometry: Any) -> tuple[float, float] | None:
    coords = _geometry_coordinates(geometry)
    while isinstance(coords, (list, tuple)) and coords and isinstance(coords[0], (list, tuple)):
        coords = coords[0]
    if (
        isinstance(coords, (list, tuple))
        and len(coords) >= 2
        and all(isinstance(v, (int, float)) for v in coords[:2])
    ):
        return (float(coords[0]), float(coords[1]))
    return None


def _geometry_last_vertex(geometry: Any) -> tuple[float, float] | None:
    coords = _geometry_coordinates(geometry)
    while isinstance(coords, (list, tuple)) and coords and isinstance(coords[-1], (list, tuple)):
        coords = coords[-1]
    if (
        isinstance(coords, (list, tuple))
        and len(coords) >= 2
        and all(isinstance(v, (int, float)) for v in coords[:2])
    ):
        return (float(coords[0]), float(coords[1]))
    return None


