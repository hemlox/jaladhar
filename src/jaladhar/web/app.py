def _normalize_row(
    row: dict[str, Any],
    *,
    number: int,
    repo_root: Path,
    requirements: DepthProductRequirements,
) -> dict[str, Any]:
    required = {
        "run_id",
        "segment_id",
        "band_low_cm",
        "band_high_cm",
        "confidence",
        "flood_status",
        "valid_time_utc",
        "issue_time_utc",
        "forecast_lead_minutes",
        "source_manifest_path",
    }
    missing = sorted(key for key in required if key not in row or row[key] in (None, ""))
    if missing:
        raise ContractViolation(f"depth product row {number} missing fields: {', '.join(missing)}")

    segment_id = _parse_int(row["segment_id"], field="segment_id", row_number=number)
    band_low = _parse_int(row["band_low_cm"], field="band_low_cm", row_number=number)
    band_high = _parse_int(row["band_high_cm"], field="band_high_cm", row_number=number)
    lead = _parse_int(
        row["forecast_lead_minutes"], field="forecast_lead_minutes", row_number=number
    )
    if segment_id < 1:
        raise ContractViolation(f"segment_id at row {number} must be positive")
    if band_low < 0 or band_high < 0 or band_low > band_high:
        raise ContractViolation(
            f"depth band at row {number} is not an ordered non-negative cm band"
        )
    if not 0 <= lead <= MAX_FORECAST_LEAD_MINUTES:
        raise ContractViolation(f"forecast_lead_minutes at row {number} must be within 0-180")

    confidence = str(row["confidence"])
    flood_status = str(row["flood_status"])
    if confidence not in {"modeled_direct", "modeled_interpolated", "no_data"}:
        raise ContractViolation(f"confidence at row {number} is not a frozen enum value")
    if confidence == "modeled_interpolated":
        raise ContractViolation(
            f"modeled_interpolated at row {number} is reserved and cannot be produced in v1"
        )
    if flood_status not in {"flooded", "not_flooded", "unknown"}:
        raise ContractViolation(f"flood_status at row {number} is not a frozen enum value")

    if confidence == "no_data":
        if flood_status != "unknown" or (band_low, band_high) != (0, 0):
            raise ContractViolation(
                f"no_data row {number} must be unknown with band [0, 0], got "
                f"{flood_status!r} [{band_low}, {band_high}]"
            )
    elif flood_status == "unknown":
        raise ContractViolation(f"modeled row {number} cannot have flood_status=unknown")
    if flood_status == "flooded" and band_high < requirements.flood_threshold_cm:
        raise ContractViolation(
            f"flooded row {number} has band_high_cm below the frozen flood rule"
        )

    valid_time = _parse_timestamp(row["valid_time_utc"], field="valid_time_utc", row_number=number)
    issue_time = _parse_timestamp(row["issue_time_utc"], field="issue_time_utc", row_number=number)
    if lead == 0 and issue_time < valid_time:
        raise ContractViolation(f"nowcast row {number} has issue_time_utc before valid_time_utc")
    if lead > 0 and issue_time > valid_time:
        raise ContractViolation(f"forecast row {number} has issue_time_utc after valid_time_utc")

    run_id = row["run_id"]
    if not isinstance(run_id, str) or not run_id.strip():
        raise ContractViolation(f"run_id at row {number} must be a non-empty string")
    source_manifest = row["source_manifest_path"]
    _manifest_path(repo_root, source_manifest)

    normalized = dict(row)
    normalized.update(
        {
            "run_id": run_id,
            "segment_id": segment_id,
            "band_low_cm": band_low,
            "band_high_cm": band_high,
            "confidence": confidence,
            "flood_status": flood_status,
            "valid_time_utc": valid_time.isoformat().replace("+00:00", "Z"),
            "issue_time_utc": issue_time.isoformat().replace("+00:00", "Z"),
            "forecast_lead_minutes": lead,
            "source_manifest_path": str(source_manifest),
        }
    )
    return normalized


@dataclass(frozen=True)
class Snapshot:

    path: Path
    run_id: str
    lead_minutes: int
    rows: tuple[dict[str, Any], ...]
    manifest_path: Path
    manifest: dict[str, Any]
    manifest_view: dict[str, Any]


def _load_snapshot(
    path: Path,
    *,
    repo_root: Path,
    lookup_ids: set[int],
    contract_path: Path,
    requirements: DepthProductRequirements,
) -> Snapshot:
    raw_rows = _read_product_rows(path)
    if not raw_rows:
        raise ContractViolation(f"depth product is empty: {_repo_relative(path, repo_root)}")
    rows = tuple(
        _normalize_row(
            row,
            number=number,
            repo_root=repo_root,
            requirements=requirements,
        )
        for number, row in enumerate(raw_rows, start=2)
    )
    run_ids = {row["run_id"] for row in rows}
    if len(run_ids) != 1:
        raise ContractViolation("depth product contains more than one run_id")
    source_paths = {row["source_manifest_path"] for row in rows}
    if len(source_paths) != 1:
        raise ContractViolation("depth product contains more than one source_manifest_path")
    leads = {row["forecast_lead_minutes"] for row in rows}
    if len(leads) != 1:
        raise ContractViolation(
            "one product file contains more than one forecast lead; the frozen contract "
            "requires one row per expected segment set, so supply separate immutable files "
            "for the slider"
        )
    valid_times = {row["valid_time_utc"] for row in rows}
    issue_times = {row["issue_time_utc"] for row in rows}
    if len(valid_times) != 1 or len(issue_times) != 1:
        raise ContractViolation(
            "depth product snapshot metadata changes valid_time_utc or issue_time_utc "
            "within one product file"
        )
    ids = [row["segment_id"] for row in rows]
    if len(set(ids)) != len(ids):
        raise ContractViolation("depth product contains duplicate segment_id values")
    product_ids = set(ids)
    if product_ids != lookup_ids:
        missing = len(lookup_ids - product_ids)
        unexpected = len(product_ids - lookup_ids)
        raise ContractViolation(
            "product segment_id set disagrees with realized lookup "
            f"(missing={missing}, unexpected={unexpected})"
        )

    run_id = next(iter(run_ids))
    manifest_path = _manifest_path(repo_root, next(iter(source_paths)))
    manifest_payload = _load_json(manifest_path, label="source manifest")
    if not isinstance(manifest_payload, dict):
        raise ContractViolation(f"source manifest is not an object: {manifest_path}")
    manifest = cast(dict[str, Any], manifest_payload)
    manifest_view = _validate_manifest(
        manifest,
        manifest_path,
        repo_root=repo_root,
        run_id=run_id,
        rows=rows,
        lookup_ids=lookup_ids,
        contract_path=contract_path,
    )
    return Snapshot(
        path=path,
        run_id=run_id,
        lead_minutes=next(iter(leads)),
        rows=rows,
        manifest_path=manifest_path,
        manifest=manifest,
        manifest_view=manifest_view,
    )


def _candidate_products(repo_root: Path, product: Path | None) -> list[Path]:
    if product is not None:
        resolved = _safe_repo_path(product, repo_root, label="product")
        if not resolved.exists():
            return []
        if resolved.is_dir():
            return sorted(
                path
                for path in resolved.iterdir()
                if path.is_file() and PRODUCT_FILE_RE.fullmatch(path.name)
            )
        if resolved.is_file() and PRODUCT_FILE_RE.fullmatch(resolved.name):
            stem = resolved.with_suffix("")
            return sorted(
                path
                for path in (stem.with_suffix(".csv"), stem.with_suffix(".json"))
                if path.is_file()
            )
        raise DashboardError(
            f"product must be a segment_status CSV/JSON or its products directory: {product}"
        )

    candidates = [
        path for path in repo_root.glob("runs/**/products/segment_status*.csv") if path.is_file()
    ]
    candidates.extend(
        path for path in repo_root.glob("runs/**/products/segment_status*.json") if path.is_file()
    )
    return sorted(set(candidates))


class GeometryIndex:

    def __init__(self, path: Path | None, *, repo_root: Path) -> None:
        self.path = path
        self.repo_root = repo_root
        self._features: dict[int, dict[str, Any]] | None = None
        self.crs: str | None = None
        self.error: str | None = None
        if path is not None:
            try:
                self.path = _safe_repo_path(path, repo_root, label="geometry")
                if not self.path.is_file():
                    raise DashboardError(f"geometry artifact does not exist: {path}")
            except (DashboardError, OSError) as exc:
                self.error = str(exc)

    @property
    def available(self) -> bool:
        return self.path is not None and self.error is None

    def _read(self) -> None:
        if self._features is not None or not self.available:
            return
        assert self.path is not None
        if self.path.suffix.lower() in {".json", ".geojson"}:
            payload = _load_json(self.path, label="geometry artifact")
            features = payload.get("features") if isinstance(payload, dict) else None
            if not isinstance(features, list):
                raise DashboardError(
                    f"geometry JSON is not a GeoJSON FeatureCollection: {self.path}"
                )
            result: dict[int, dict[str, Any]] = {}
            for feature in features:
                if not isinstance(feature, dict) or not isinstance(feature.get("properties"), dict):
                    continue
                raw_id = feature["properties"].get("segment_id", feature.get("id"))
                try:
                    segment_id = _parse_int(raw_id, field="geometry.segment_id")
                except ContractViolation:
                    continue
                if feature.get("geometry") is not None:
                    result[segment_id] = cast(dict[str, Any], feature["geometry"])
            self._features = result
            self.crs = "GeoJSON CRS (producer declaration not present in frozen product contract)"
            return

        try:
            import fiona
        except ImportError as exc:
            raise DashboardError(
                "fiona is required to read a GeoPackage geometry artifact"
            ) from exc
        try:
            layers = fiona.listlayers(self.path)
            if not layers:
                raise DashboardError(f"geometry GeoPackage has no layers: {self.path}")
            result = {}
            with fiona.open(self.path, layer=layers[0]) as source:
                self.crs = source.crs_wkt or str(source.crs) or None
                for feature in source:
                    properties = dict(feature.get("properties") or {})
                    raw_id = properties.get("segment_id", feature.get("id"))
                    try:
                        segment_id = _parse_int(raw_id, field="geometry.segment_id")
                    except ContractViolation:
                        continue
                    geometry = feature.get("geometry")
                    if geometry is not None:
                        result[segment_id] = dict(geometry)
        except (OSError, ValueError) as exc:
            raise DashboardError(f"could not read geometry artifact {self.path}: {exc}") from exc
        self._features = result

    def for_ids(self, ids: Iterable[int]) -> dict[int, dict[str, Any]]:
        self._read()
        if self._features is None:
            return {}
        return {
            segment_id: self._features[segment_id]
            for segment_id in ids
            if segment_id in self._features
        }


def _flat_probe_reason(twins: dict[str, Path], *, repo_root: Path) -> str | None:

    try:
        if set(twins) != {".csv", ".json"}:
            return "incomplete CSV/JSON twin pair"
        manifest_path = next(iter(twins.values())).parent.parent / "manifest.json"
        payload = json.loads(manifest_path.read_text(encoding="utf-8"))
        if not isinstance(payload, dict):
            return "run manifest is not an object"
        if payload.get("status") != "completed":
            return f"manifest status is {payload.get('status')!r}, not 'completed'"
        admission_relative = payload.get("uncoupled_baseline_admission_path")
        admission_sha = payload.get("uncoupled_baseline_admission_sha256")
        if isinstance(admission_relative, str) and isinstance(admission_sha, str):
            actual = sha256_file(repo_root / admission_relative)
            if actual != admission_sha:
                return (
                    "stale uncoupled_baseline_admission_sha256 "
                    f"{admission_sha[:12]}... vs realized admission bytes {actual[:12]}..."
                )
        return None
    except (ContractViolation, DashboardError, OSError, json.JSONDecodeError) as exc:
        return str(exc)


class DashboardStore:

    def __init__(
        self,
        *,
        repo_root: Path = REPO_ROOT,
        product: Path | None = None,
        geometry: Path | None = None,
        gate_report: Path | None = None,
    ) -> None:
        self.repo_root = repo_root.resolve()
        self.product_argument = product
        self.contract = _contract(self.repo_root)
        self.contract_path = self.repo_root / "configs" / "contracts" / "depth_product.json"
        self.requirements = load_requirements(self.contract_path)
        self.geometry = GeometryIndex(geometry, repo_root=self.repo_root)
        self.gate_report_argument = gate_report
        self.snapshots: tuple[Snapshot, ...] = ()
        self.error: str | None = None
        self.skipped_candidates: list[dict[str, str]] = []
        # distinct-lead rule correctly refuses for a replay time series.
        self.series = detect_series(product, repo_root=self.repo_root)
        if self.series is not None:
            if product is None:
                self._annotate_flat_candidates()
            return
        try:
            lookup_ids = _lookup_ids(self.repo_root)
            self.snapshots = self._load_snapshots_quarantined(lookup_ids)
            if not self.snapshots and self.skipped_candidates:
                raise ContractViolation(
                    "no candidate depth product validated: "
                    + "; ".join(
                        f"{entry['candidate']}: {entry['reason']}"
                        for entry in self.skipped_candidates
                    )
                )
        except (ContractViolation, DashboardError, OSError, json.JSONDecodeError) as exc:
            self.error = str(exc)

    def _record_skip(self, candidate: str, kind: str, disposition: str, reason: str) -> None:
        self.skipped_candidates.append(
            {
                "candidate": candidate,
                "kind": kind,
                "disposition": disposition,
                "reason": reason,
            }
        )
        if disposition == "skipped":
            typer.echo(f"dashboard: skipped candidate {candidate}: {reason}", err=True)

    def _manifest_recency(self, stem: Path) -> tuple[str, str]:

        manifest_path = stem.parent.parent / "manifest.json"
        try:
            payload = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return ("", "")
        if not isinstance(payload, dict):
            return ("", "")
        return (
            str(payload.get("end_time_iso") or payload.get("start_time_iso") or ""),
            "",
        )

    def _flat_probe_disposition(self, twins: dict[str, Path]) -> str | None:
        return _flat_probe_reason(twins, repo_root=self.repo_root)

    def _annotate_flat_candidates(self) -> None:
        candidates = _candidate_products(self.repo_root, None)
        grouped: dict[Path, dict[str, Path]] = {}
        for path in candidates:
            grouped.setdefault(path.with_suffix(""), {})[path.suffix.lower()] = path
        ordered = sorted(
            grouped.items(),
            key=lambda item: (self._manifest_recency(item[0]), str(item[0])),
            reverse=True,
        )
        for stem, twins in ordered:
            reason = self._flat_probe_disposition(twins)
            relative = _repo_relative(stem, self.repo_root)
            if reason is not None:
                self._record_skip(relative, "flat_twin", "skipped", reason)
            else:
                self._record_skip(
                    relative,
                    "flat_twin",
                    "not_selected",
                    f"a valid frame series was selected ({SELECTION_ORDER}); these flat "
                    "twins were not loaded and are NOT claimed validated in this mode",
                )

    def _load_snapshots_quarantined(self, lookup_ids: set[int]) -> tuple[Snapshot, ...]:
        candidates = _candidate_products(self.repo_root, self.product_argument)
        if not candidates:
            return ()
        grouped: dict[Path, dict[str, Path]] = {}
        for path in candidates:
            grouped.setdefault(path.with_suffix(""), {})[path.suffix.lower()] = path
        ordered = sorted(
            grouped.items(),
            key=lambda item: (self._manifest_recency(item[0]), str(item[0])),
            reverse=True,
        )
        loaded: list[Snapshot] = []
        seen_leads: dict[int, str] = {}
        for stem, twins in ordered:
            relative = _repo_relative(stem, self.repo_root)
            try:
                if set(twins) != {".csv", ".json"}:
                    raise ContractViolation(f"incomplete CSV/JSON twin pair for {relative}")
                csv_snapshot = _load_snapshot(
                    twins[".csv"],
                    repo_root=self.repo_root,
                    lookup_ids=lookup_ids,
                    contract_path=self.contract_path,
                    requirements=self.requirements,
                )
                json_snapshot = _load_snapshot(
                    twins[".json"],
                    repo_root=self.repo_root,
                    lookup_ids=lookup_ids,
                    contract_path=self.contract_path,
                    requirements=self.requirements,
                )
                csv_rows = [
                    {key: value for key, value in row.items() if key != "_geometry"}
                    for row in csv_snapshot.rows
                ]
                json_rows = [
                    {key: value for key, value in row.items() if key != "_geometry"}
                    for row in json_snapshot.rows
                ]
                if csv_rows != json_rows:
                    raise ContractViolation(f"CSV/JSON depth-product twins disagree for {relative}")
                lead = json_snapshot.lead_minutes
                if lead in seen_leads:
                    raise ContractViolation(
                        f"duplicate forecast_lead_minutes={lead}; the newer product "
                        f"{seen_leads[lead]} keeps this lead ({SELECTION_ORDER})"
                    )
            except (ContractViolation, OSError, json.JSONDecodeError) as exc:
                self._record_skip(relative, "flat_twin", "skipped", str(exc))
                continue
            seen_leads[lead] = relative
            loaded.append(json_snapshot)
        return tuple(sorted(loaded, key=lambda snapshot: snapshot.lead_minutes))

    @property
    def status(self) -> str:
        if self.error is not None:
            return "error"
        if self.series is not None:
            return "ready" if self.series.ready else "empty"
        return "ready" if self.snapshots else "empty"

    def state_payload(self) -> dict[str, Any]:
        candidate_outcome = {
            "skipped_candidates": list(self.skipped_candidates),
            "selection_order": SELECTION_ORDER,
        }
        if self.error is not None:
            return {
                "status": "error",
                "message": self.error,
                **candidate_outcome,
                "contract_gaps": list(CONTRACT_GAPS),
            }
        if self.series is not None:
            series_meta = self.series.meta_payload()
            if not series_meta["available"]:
                return {
                    "status": "empty",
                    "mode": "series",
                    "message": "The frame series could not be accepted: "
                    + str(series_meta["error"]),
                    "series": series_meta,
                    **candidate_outcome,
                    "contract_gaps": list(CONTRACT_GAPS),
                }
            gate = self._scientific_gate_summary()
            state = {
                "status": "ready",
                "mode": "series",
                "readiness_kind": "product_bytes_loaded_not_gate_acceptance",
                "message": "Contract-shaped frame series loaded; this is not gate acceptance.",
                "series": series_meta,
                **candidate_outcome,
                "geometry": {
                    "available": self.geometry.available,
                    "path": (
                        _repo_relative(self.geometry.path, self.repo_root)
                        if self.geometry.path is not None
                        else None
                    ),
                    "error": self.geometry.error,
                    "browser_scope": "bounded_preview_not_full_city",
                },
                "scientific_gate": gate,
                "contract": {
                    "name": self.contract.get("name"),
                    "version": self.contract.get("version"),
                    "path": "configs/contracts/depth_product.json",
                },
                "contract_gaps": list(CONTRACT_GAPS),
            }
            open_anomaly = self._open_anomaly_summary()
            if open_anomaly is not None:
                state["open_anomaly"] = open_anomaly
            return state
        if not self.snapshots:
            requested = (
                _repo_relative(self.product_argument, self.repo_root)
                if self.product_argument
                else None
            )
            message = (
                "No solver segment product is available. The dashboard is intentionally "
                "empty until a contract-valid depth product and source manifest exist."
            )
            return {
                "status": "empty",
                "message": message,
                "requested_product": requested,
                **candidate_outcome,
                "contract": {
                    "name": self.contract.get("name"),
                    "version": self.contract.get("version"),
                    "path": "configs/contracts/depth_product.json",
                },
                "contract_gaps": list(CONTRACT_GAPS),
            }
        gate = self._scientific_gate_summary()
        state = {
            "status": "ready",
            "readiness_kind": "product_bytes_loaded_not_gate_acceptance",
            "message": "Contract-valid product bytes are loaded; this is not gate acceptance.",
            "leads": [snapshot.lead_minutes for snapshot in self.snapshots],
            **candidate_outcome,
            "snapshots": [
                {
                    "lead_minutes": snapshot.lead_minutes,
                    "run_id": snapshot.run_id,
                    "product_path": _repo_relative(snapshot.path, self.repo_root),
                    "source_manifest_path": _repo_relative(snapshot.manifest_path, self.repo_root),
                    "manifest": snapshot.manifest_view,
                    "product_label": snapshot.manifest.get("product_label"),
                    "forcing_kind": snapshot.manifest.get("forcing_kind"),
                    "temporal_aggregation": snapshot.manifest.get("temporal_aggregation"),
                }
                for snapshot in self.snapshots
            ],
            "geometry": {
                "available": self.geometry.available,
                "path": (
                    _repo_relative(self.geometry.path, self.repo_root)
                    if self.geometry.path is not None
                    else None
                ),
                "error": self.geometry.error,
                "browser_scope": "bounded_preview_not_full_city",
            },
            "scientific_gate": gate,
            "contract": {
                "name": self.contract.get("name"),
                "version": self.contract.get("version"),
                "path": "configs/contracts/depth_product.json",
            },
            "contract_gaps": list(CONTRACT_GAPS),
        }
        open_anomaly = self._open_anomaly_summary()
        if open_anomaly is not None:
            state["open_anomaly"] = open_anomaly
        return state

    def _scientific_gate_summary(self) -> dict[str, Any]:
        if self.gate_report_argument is None:
            referenced = self._referenced_event_gate_summary()
            if referenced is not None:
                return referenced
            return {
                "status": "unavailable",
                "g1_status": "UNAVAILABLE",
                "signed_g3_status": "UNAVAILABLE",
                "reason": "no product-bound gate report configured",
            }
        try:
            path = _safe_repo_path(self.gate_report_argument, self.repo_root, label="gate report")
            payload = _load_json(path, label="gate report")
            if not isinstance(payload, dict):
                raise ContractViolation("gate report must be a JSON object")
            product_hashes: set[str] = set()
            for snapshot in self.snapshots:
                product_hashes.add(sha256_file(snapshot.path))
                csv_twin = snapshot.path.with_suffix(".csv")
                if csv_twin.is_file():
                    product_hashes.add(sha256_file(csv_twin))
            bound_hash = payload.get("input_sha256", {}).get("depth_product")
            if bound_hash not in product_hashes:
                raise ContractViolation("gate report is not bound to a selected product twin")
            event_scoped = any(
                snapshot.manifest.get("temporal_aggregation") == EVENT_MAXIMUM_AGGREGATION
                for snapshot in self.snapshots
            )
            raw_g1 = payload.get("g1", {}).get("status")
            return {
                "status": "loaded_not_accepted",
                "g1_status": _event_maximum_label(raw_g1) if event_scoped else raw_g1,
                "signed_g3_status": payload.get("g3", {}).get("status"),
                "bound_product_sha256": bound_hash,
                "report_path": _repo_relative(path, self.repo_root),
                "report_sha256": sha256_file(path),
                "scope": EVENT_MAXIMUM_SCOPE if event_scoped else "product_binding",
            }
        except (ContractViolation, DashboardError, OSError) as exc:
            referenced = self._referenced_event_gate_summary()
            if referenced is not None:
                return referenced
            return {
                "status": "invalid",
                "g1_status": "UNAVAILABLE",
                "signed_g3_status": "UNAVAILABLE",
                "reason": str(exc),
            }

    def _referenced_event_gate_summary(self) -> dict[str, Any] | None:
        if self.series is None:
            return None
        ref = self.series.manifest.get("event_maximum_gate_reference")
        if not isinstance(ref, dict):
            return None
        try:
            raw_path = ref.get("gate_report_path")
            if not isinstance(raw_path, str) or not raw_path.strip():
                raise ContractViolation("annotation carries no gate_report_path")
            path = _safe_repo_path(Path(raw_path), self.repo_root, label="annotated gate report")
            payload = _load_json(path, label="annotated gate report")
            if not isinstance(payload, dict):
                raise ContractViolation("annotated gate report must be a JSON object")
            realized_sha = sha256_file(path)
            return {
                "status": "loaded_not_accepted",
                "g1_status": _event_maximum_label(payload.get("g1", {}).get("status")),
                "signed_g3_status": payload.get("g3", {}).get("status"),
                "bound_product_sha256": ref.get("event_product_sha256"),
                "report_path": _repo_relative(path, self.repo_root),
                "report_sha256": realized_sha,
                "reference_stale": realized_sha != ref.get("gate_report_sha256"),
                "scope": ref.get("scope"),
            }
        except (ContractViolation, DashboardError, OSError) as exc:
            return {
                "status": "invalid",
                "g1_status": "UNAVAILABLE",
                "signed_g3_status": "UNAVAILABLE",
                "reason": f"event_maximum_gate_reference unusable: {exc}",
            }

    def _open_anomaly_summary(self) -> dict[str, Any] | None:
        "The ACTIVE run manifest's flagged unexplained result, verbatim (M3). Sourced only from producer/adjudicator-written normalized blocks -- ``open_anomaly`` (frames_v2 producer / carryover annotation) or ``owner_adjudication.open_anomaly`` (the adopted v6 record, the residual_anomaly equivalent for flat runs). A bare ``residual_anomaly`` block is deliberately NOT reshaped here: it lacks status/policy/range fields and inventing them would fabricate provenance. An incomplete or non-OPEN block renders nothing -- designed absence, never a partial card."  # noqa: E501
        if self.series is not None:
            manifest = self.series.manifest
            source_manifest = _repo_relative(self.series.manifest_path, self.repo_root)
        elif self.snapshots:
            snapshot = self.snapshots[-1]
            manifest = snapshot.manifest
            source_manifest = _repo_relative(snapshot.manifest_path, self.repo_root)
        else:
            return None
        block = manifest.get("open_anomaly")
        if not isinstance(block, dict):
            owner = manifest.get("owner_adjudication")
            block = owner.get("open_anomaly") if isinstance(owner, dict) else None
        if not isinstance(block, dict) or block.get("status") != "OPEN":
            return None
        n_segments = block.get("n_segments_gt300cm")
        range_cm = block.get("range_cm")
        policy = block.get("policy")
        if not isinstance(range_cm, list) or len(range_cm) != 2:
            low = block.get("range_cm_low_bound_cm")
            high = block.get("range_cm_high_cm")
            range_cm = [low, high]
        if (
            not isinstance(n_segments, int)
            or isinstance(n_segments, bool)
            or not all(isinstance(bound, int) for bound in range_cm)
            or not isinstance(policy, str)
            or not policy
        ):
            return None
        return {
            "status": "OPEN",
            "n_segments_gt300cm": n_segments,
            "range_cm": list(range_cm),
            "policy": policy,
            "source_manifest": source_manifest,
        }

    def product_blob(self, lead: int | None = None) -> bytes:

        import numpy as np

        snapshot = self._snapshot(lead)
        rows = snapshot.rows
        n = len(rows)
        ids = np.fromiter((row["segment_id"] for row in rows), dtype="<u4", count=n)
        dense = n > 0 and bool(np.array_equal(ids, np.arange(1, n + 1, dtype="<u4")))
        band_low = np.fromiter((row["band_low_cm"] for row in rows), dtype="<u2", count=n)
        band_high = np.fromiter((row["band_high_cm"] for row in rows), dtype="<u2", count=n)
        status_code = {"not_flooded": 0, "flooded": 1, "unknown": 2}
        status = np.fromiter(
            (status_code[row["flood_status"]] for row in rows), dtype="u1", count=n
        )
        header = np.asarray([n, 1 if dense else 0, snapshot.lead_minutes], dtype="<i4").tobytes()
        parts = [header]
        if not dense:
            parts.append(ids.tobytes())
        parts.extend((band_low.tobytes(), band_high.tobytes(), status.tobytes()))
        return b"".join(parts)

    def _snapshot(self, lead: int | None) -> Snapshot:
        if not self.snapshots:
            raise DashboardError("no contract-valid solver output is available")
        if lead is None:
            return self.snapshots[0]
        for snapshot in self.snapshots:
            if snapshot.lead_minutes == lead:
                return snapshot
        raise DashboardError(f"no realized product exists for forecast lead {lead}")

    def series_frame_blob(self, index: int) -> bytes:
        try:
            return self.series.frame_blob(index)
        except Exception as exc:
            raise DashboardError(str(exc)) from exc

    def series_segment_payload(self, index: int, segment_id: int) -> dict[str, Any]:
        row = self.series.lookup_segment(index, segment_id)
