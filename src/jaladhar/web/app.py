# In-process cache for the lane builders, keyed by (kind, run_id, resolved
# frame). The builders re-read the centreline gpkg and product CSVs per call;
# caching per realized (run, frame) keeps repeated UI requests off that path.
_LANES_CACHE_LOCK = threading.Lock()
_LANES_CACHE: dict[tuple[str, str, str], dict[str, Any]] = {}


def _active_product_source(store: DashboardStore) -> Any:
    """Resolve the lane modules' ProductSource from the store's realized state.

    Series run dir when a ready frame series owns the store, else the flat
    products directory of the newest selected snapshot. No product -> honest
    refusal; nothing is built from absent state.
    """
    if store.series is not None and store.series.ready:
        return resolve_product_source(store.series.run_dir, repo_root=store.repo_root)
    if store.snapshots:
        products_dir = store.snapshots[-1].path.parent
        return resolve_product_source(products_dir, repo_root=store.repo_root)
    raise DashboardError("no realized depth product is loaded; watchlist/intersections refused")


def _resolve_lane_frame(source: Any, frame_param: str) -> tuple[Any, str]:
    """(lane frame value, cache-key suffix) from a tag|index|"held" param.

    "held" (the default, what watchlist.js pins until a frame event arrives)
    means the timeline's hold-at-end frame: the LAST frame of a series; flat
    sources have no frames, so the parameter is inert there.
    """
    raw = (frame_param or "").strip() or "held"
    if raw.lower() == "held":
        if getattr(source, "kind", "") == "frame" and source.frames:
            return len(source.frames) - 1, f"held:{source.frames[-1].tag}"
        return None, "flat"
    return raw, f"given:{raw}"


def _lane_payload(store: DashboardStore, kind: str, frame_param: str) -> dict[str, Any]:
    source = _active_product_source(store)
    frame_value, frame_key = _resolve_lane_frame(source, frame_param)
    cache_key = (kind, str(source.run_id), frame_key)
    with _LANES_CACHE_LOCK:
        cached = _LANES_CACHE.get(cache_key)
    if cached is not None:
        return cached
    if kind == "watchlist":
        payload = build_watchlist(source, frame_value, repo_root=store.repo_root)
    else:
        payload = build_intersections(source, frame_value, repo_root=store.repo_root)
    with _LANES_CACHE_LOCK:
        _LANES_CACHE[cache_key] = payload
    return payload


